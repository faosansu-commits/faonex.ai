function createLocaleStore() {
	const { subscribe, set: setStore } = writable('th');

	function apply(value) {
		const next = value === 'en' ? 'en' : 'th';
		setStore(next);
		if (typeof localStorage !== 'undefined') {
			localStorage.setItem(STORAGE_KEY, next);
		}
		if (typeof document !== 'undefined') {
			document.documentElement.lang = next;
		}
	}

	function init() {
		if (typeof localStorage === 'undefined') return;
		const saved = localStorage.getItem(STORAGE_KEY);
		apply(saved === 'en' ? 'en' : 'th');
	}

	return { subscribe, init, set: apply };
}

export const locale = createLocaleStore();

export const t = derived(locale, ($locale) => (key) => {
	const table = dict[$locale] || dict.th;
	return table[key] ?? dict.th[key] ?? key;
});
